import asyncio
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(args=['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader'])
        pg = await b.new_page(viewport={'width':1280,'height':800})
        errs=[]; pg.on('pageerror', lambda e: errs.append(str(e))); pg.on('console', lambda m: errs.append(m.text) if m.type=='error' and 'ERR_FAILED' not in m.text else None)
        await pg.route('**/fonts.g*/**', lambda r: r.abort())
        await pg.goto('file:///home/claude/valley/dist/三年山徑_大同國中泰雅文化課程.html', wait_until='commit', timeout=120000)
        await pg.wait_for_timeout(9000)
        await pg.screenshot(path='shots/t-tour.png', timeout=180000)
        for _ in range(2): await pg.click('#tourNext')
        await pg.wait_for_timeout(800); await pg.screenshot(path='shots/t-tour3.png', timeout=180000)
        await pg.click('#tourSkip')
        await pg.click('#listBtn'); await pg.wait_for_timeout(1500); await pg.screenshot(path='shots/t-list.png', timeout=180000)
        await pg.click('#listClose')
        await pg.click('#pathBtn'); await pg.wait_for_timeout(1500)
        await pg.evaluate("document.querySelector('#weaveChips button').click()")
        await pg.wait_for_timeout(7000); await pg.screenshot(path='shots/t-path.png', timeout=180000)
        await pg.click('#pathClose')
        await pg.evaluate("document.querySelectorAll('.ilabel')[7].click()")
        await pg.wait_for_timeout(4000); await pg.screenshot(path='shots/t-isl.png', timeout=180000)
        await pg.click('#close'); await pg.wait_for_timeout(1500)
        await pg.evaluate("window.__dbg.onPerson(window.__dbg.walkers[3].g)")
        await pg.wait_for_timeout(1000); await pg.screenshot(path='shots/t-bubble.png', timeout=180000)
        await pg.click('#findBtn'); await pg.wait_for_timeout(2500); await pg.screenshot(path='shots/t-game.png', timeout=180000)
        await pg.evaluate("window.__dbg.onPerson(window.__dbg.guide.g)")
        await pg.wait_for_timeout(3000); await pg.screenshot(path='shots/t-found.png', timeout=180000)
        print(errs)
        await b.close()
asyncio.run(main())
