const { chromium } = require('playwright');
const D=process.env.SHOTS||'/tmp/shots/';
const vp=process.argv[2]||'d';
(async()=>{
 const b=await chromium.launch({args:['--use-gl=swiftshader','--enable-unsafe-swiftshader']});
 const p=await b.newPage(vp==='m'?{viewport:{width:390,height:844},hasTouch:true,isMobile:true}:{viewport:{width:1366,height:820}});
 const errs=[]; p.on('pageerror',e=>errs.push(e.message)); p.on('console',m=>{if(m.type()==='error'&&!/ERR_TUNNEL|Failed to load/.test(m.text()))errs.push(m.text())});
 await p.addInitScript(()=>{try{localStorage.setItem('eval3d-tour','1')}catch(e){}});
 await p.goto('http://localhost:8765/?time=day&debug'); await p.waitForTimeout(10000);
 const shot=async(n)=>{await p.screenshot({path:D+`f_${vp}_${n}.png`,timeout:150000});};
 await shot('0over');
 await p.click('#listBtn'); await p.waitForTimeout(800);
 await p.click('[data-tab="rel"]'); await p.waitForTimeout(800);
 await shot('1rel');
 await p.click('[data-rel="5"]'); await p.waitForTimeout(4500);
 await shot('2relfocus');
 console.log('visible walkers', await p.evaluate(()=>window.__e3d.walkers.filter(w=>w.g.visible).map(w=>w.roleName)));
 await p.click('#listClose'); await p.waitForTimeout(500);
 await p.click('#viewBtn'); await p.waitForTimeout(600);
 await shot('3view');
 await p.click('label.vopt:nth-of-type(1)'); await p.waitForTimeout(800);
 console.log('hide-labels', await p.evaluate(()=>document.body.className));
 await p.click('label.vopt:nth-of-type(1)');
 await p.keyboard.press('Escape'); await p.waitForTimeout(500);
 await p.click('#playBtn'); await p.waitForTimeout(4000);
 await shot('5play0');
 for (let i=0;i<4;i++){ await p.click('#playNext'); await p.waitForTimeout(300);} await p.waitForTimeout(4000);
 await shot('6play4');
 for (let i=0;i<5;i++){ await p.click('#playNext'); await p.waitForTimeout(300);} await p.waitForTimeout(4500);
 await shot('7play9');
 console.log('play', await p.evaluate(()=>document.querySelector('#playCount').textContent+' '+document.querySelector('#playTitle').textContent));
 await p.keyboard.press('Escape'); await p.waitForTimeout(600);
 console.log('after play', await p.evaluate(()=>document.body.className+' '+document.querySelector('#play').hidden));
 console.log('errs',errs); await b.close();
})();
